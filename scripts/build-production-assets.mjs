import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const output=path.join(root,'production-public');
const html=fs.readFileSync(path.join(root,'preview-public/index.html'),'utf8');
if(!html.includes('SmartTrade AI · v0.14 Preview'))throw Error('Review production branding before building changed assets');
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,'index.html'),html.replace('SmartTrade AI · v0.14 Preview','SmartTrade AI · v0.14'));
fs.copyFileSync(path.join(root,'preview-public/account-client.js'),path.join(output,'account-client.js'));
console.log('Built production simulation UI and account client; Preview assets unchanged.');
